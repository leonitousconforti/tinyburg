/**
 * Helpers for an SDK's `frida/Generate.ts`, which regenerates some of the
 * SDK's source files from its game's own data. It runs the game on insight's
 * emulator with the SDK's agent (`frida/Agent.ts`) loaded, asks the agent for
 * the data and writes it between the two separator lines of each file.
 *
 * @since 1.0.0
 */

import { Array, Clock, Effect, FileSystem, Order, type PlatformError, Record, pipe } from "effect";
import { RpcClientError } from "effect/rpc";

import { FridaDevice, FridaSessionError } from "@efffrida/frida-tools";
import { GooglePlayApi } from "@efffrida/gplayapi";

import { layerAgent, layerDevice, layerPlay } from "./index.ts";

const SEPARATOR = "//////////////////////////////////////////////////////////////////";

/**
 * The comment each generated file starts with. {@link main} reads the
 * version back out of it to skip a game whose files are up to date.
 *
 * @since 1.0.0
 * @category Generate
 */
export const banner = (game: string, version: string): Effect.Effect<string> =>
    Effect.map(
        Clock.currentTimeMillis,
        (now) => `/**
 * This file was auto-generated by a frida agent.
 *
 * Generated On: ${new Date(now).toUTCString()}
 *
 * With ${game} Version: ${version}
 */
`
    );

/**
 * Replaces what is between the two separator lines of a file.
 *
 * @since 1.0.0
 * @category Generate
 */
export const replaceGeneratedContent = (
    filePath: string,
    newContent: string
): Effect.Effect<void, PlatformError.PlatformError, FileSystem.FileSystem> =>
    Effect.gen(function* () {
        const fileSystem = yield* FileSystem.FileSystem;
        const existingContent = yield* fileSystem.readFileString(filePath);
        const separatorPattern = new RegExp(`(${SEPARATOR})([\\s\\S]*?)(${SEPARATOR})`);

        if (!separatorPattern.test(existingContent)) {
            return yield* Effect.die(`Expected two separators in file: ${filePath}`);
        }

        const updatedContent = existingContent.replace(separatorPattern, `$1\n\n${newContent}\n\n$3`);
        yield* fileSystem.writeFileString(filePath, updatedContent);
    });

/**
 * Turns a record of objects keyed by name, each with a numeric `index`, into
 * a list ordered by that index, with the name as a `name` field.
 *
 * @since 1.0.0
 * @category Generate
 */
export const sortIndexable = <T extends Readonly<{ index: string }>>(
    input: Readonly<Record<string, T>>
): Array<Omit<T, "index"> & { readonly name: string }> =>
    pipe(
        input,
        Record.toEntries,
        Array.map(([name, object]) => ({ name, ...object })),
        Array.sortWith(({ index }) => Number.parseInt(index), Order.Number),
        Array.map(({ index: _index, ...rest }) => ({ ...rest }))
    );

/**
 * In stringified JSON, replaces each string value of `fieldname` that is a
 * member of `enums` with a reference to it, `typeName.Member`, so the
 * generated file refers to its enum instead of repeating the strings.
 *
 * @since 1.0.0
 * @category Generate
 */
export const replaceEnumTypeFields = (
    stringified: string,
    fieldname: string,
    enums: Readonly<Record<string, string>>,
    typeName: string
): string =>
    stringified.replace(
        new RegExp(`"${fieldname}":\\s*"(${Object.keys(enums).join("|")})"`, "g"),
        (_match, p1) => `"${fieldname}": ${typeName}.${p1}`
    );

/**
 * Whether every file was generated from this version of the game.
 *
 * @since 1.0.0
 * @category Generate
 */
export const isUpToDate = (
    files: ReadonlyArray<string>,
    game: string,
    version: string
): Effect.Effect<boolean, PlatformError.PlatformError, FileSystem.FileSystem> =>
    Effect.gen(function* () {
        const fileSystem = yield* FileSystem.FileSystem;
        const contents = yield* Effect.forEach(files, (file) => fileSystem.readFileString(file));
        return Array.every(contents, (content) => content.includes(`With ${game} Version: ${version}`));
    });

/**
 * Whether a failed generate is worth another try. A crashed frida-server
 * shows up as a failed spawn, attach, resume, load or RPC call while the
 * agent starts, and as a "detached" FridaSessionError, the cause of the
 * RpcClientError, for each RPC after that. "compile" errors come from
 * building the agent and would happen again.
 *
 * @since 1.0.0
 * @category Generate
 */
export const isRetryable = (error: unknown): boolean => {
    if (error instanceof FridaSessionError.FridaSessionError) return error.when !== "compile";
    if (!(error instanceof RpcClientError.RpcClientError) || error.reason._tag !== "RpcClientDefect") return false;
    const cause = error.reason.cause;
    return cause instanceof FridaSessionError.FridaSessionError && cause.when === "detached";
};

/**
 * @since 1.0.0
 * @category Generate
 */
export interface Options<E, R> {
    /** The game's Android package, such as `com.nimblebit.tinytower`. */
    readonly bundleIdentifier: string;
    /** The game's name, as each generated file's banner gives it. */
    readonly game: string;
    /** The SDK's agent, `new URL("./Agent.ts", import.meta.url)`. */
    readonly agent: URL;
    /** The files `generate` rewrites. */
    readonly files: ReadonlyArray<string>;
    /** Regenerate the files even if they are from the game's current version. */
    readonly force?: boolean | undefined;
    /** Asks the agent for the data and writes the files. */
    readonly generate: Effect.Effect<void, E, R>;
}

/**
 * Regenerates an SDK's files unless they are from the game's current version
 * on Google Play: boots insight's emulator, installs the game, loads the
 * SDK's agent and runs `generate`. A frida-server crash (killed, or a
 * segfault) or a crash of the game detaches the session; the emulator
 * restarts frida-server, and `generate` gets two more tries, each with a new
 * session and agent.
 *
 * @since 1.0.0
 * @category Generate
 */
export const main = <E, R>(options: Options<E, R>) =>
    Effect.gen(function* () {
        const { game } = options;
        const details = yield* GooglePlayApi.details(options.bundleIdentifier);
        const version = details.item?.details?.appDetails?.versionString;
        if (version === undefined) {
            return yield* Effect.die(`Could not fetch ${game}'s version from Google Play`);
        }

        yield* Effect.logInfo(`Most recent ${game} version on Google Play: ${version}`);
        if (options.force !== true && (yield* isUpToDate(options.files, game, version))) {
            return yield* Effect.logInfo(`Every generated file is already from ${game} ${version}`);
        }

        yield* options.generate.pipe(
            Effect.scoped,
            // Each try gets its own session and agent
            // oxlint-disable-next-line effecttsgo/strict-effect-provide
            Effect.provide(layerAgent(options.bundleIdentifier, options.agent), { local: true }),
            Effect.tapError((error) => (isRetryable(error) ? Effect.logWarning(error) : Effect.void)),
            (attempt) => Effect.andThen(FridaDevice.awaitReachable(), attempt),
            Effect.retry({ times: 2, while: isRetryable }),
            // oxlint-disable-next-line effecttsgo/strict-effect-provide
            Effect.provide(layerDevice(options.bundleIdentifier))
        );
    }).pipe(
        // An SDK's generate script is the entry point
        // oxlint-disable-next-line effecttsgo/strict-effect-provide
        Effect.provide(layerPlay)
    );
